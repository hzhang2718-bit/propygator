# GRACE-FO sphere-equivalent parameters (the study's 2026-08-13 geometry;
# experiments/extended-validation/README.md).
A_REF_M2 = 1.0013468
CR = 1.3
CD_NOMINAL = 2.3
# results_drag/window_10_storm_2026_01.txt: "dry 569.914 + gas = 595.844 kg".
MASS_KG = 595.844

# Measured (600 s cadence): drag off 547.5 m, Cd=2.3 63.8 m, sphere 34.7 m.
DRAG_OFF_BAND_M = (300.0, 900.0)
# Measured cd23/drag_off ~ 0.116, sphere/cd23 ~ 0.544. Wide margins on both.
CD23_RATIO_BOUND = 0.3
SPHERE_RATIO_BOUND = 0.9


def _run(drag: bool, cd) -> float:
    t0 = Epoch.from_iso(T0_ISO, TimeScale.TAI)
    truth = np.asarray(TRUTH_POS_M)
    state0 = State(t0, truth[0], np.asarray(TRUTH_VEL_MS)[0], Frame.ITRF).to_frame(
        Frame.EME2000
    )
    span_s = STEP_S * (len(truth) - 1)
    traj = propagate_numerical(
        state0,
        span_s,
        output_step=STEP_S,
        force_models=ForceModelConfig(
            drag=drag,
            atmosphere_model="NRLMSISE-00",
            srp=True,
            solid_tides=True,
            ocean_tides=True,
            relativity=True,
        ),
        spacecraft=SpacecraftConfig(
            mass_kg=MASS_KG,
            geometry=SpacecraftGeometry.sphere(
                area_m2=A_REF_M2,
                drag_coefficient=cd,
                reflectivity_coefficient=CR,
            ),
        ),
        integrator=IntegratorConfig.high_precision(),
        progress=False,
    )
    positions = traj.to_frame(Frame.ITRF).positions
    assert len(positions) == len(truth)
    diff = positions - truth
    return float(np.sqrt(np.mean(np.sum(diff**2, axis=1))))


def test_sphere_table_beats_naive_cd_in_storm_window(orekit):
    rms_off = _run(drag=False, cd=CD_NOMINAL)
    rms_cd23 = _run(drag=True, cd=CD_NOMINAL)
    rms_sphere = _run(drag=True, cd=VariableCd.sphere_default())

    # Sanity band on the drag-off residual: confirms the drag signal itself
    # is present at roughly the right scale (catches a broken force-model
    # wiring rather than freezing the exact number).
    assert DRAG_OFF_BAND_M[0] < rms_off < DRAG_OFF_BAND_M[1]

    # The relationship this pin exists to catch: both drag-on configs beat
    # drag-off, and the sphere table beats the naive Cd in this active window.
    assert rms_cd23 < CD23_RATIO_BOUND * rms_off
    assert rms_sphere < SPHERE_RATIO_BOUND * rms_cd23
