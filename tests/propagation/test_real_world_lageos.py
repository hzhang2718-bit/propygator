# LAGEOS-2 physical parameters (experiment README citations).
LAGEOS2_MASS_KG = 405.38
LAGEOS2_AREA_M2 = math.pi * 0.30**2
LAGEOS2_CR = 1.13

# Measured 9.3e-10 m — anything near a meter is a frame/time conversion bug.
T0_DIFF_BOUND_M = 1.0
# Measured 3.62 m RMS (Checkpoint A, tier-1 GO) — x4 margin.
DAY1_RMS_BOUND_M = 15.0


def test_lageos_conservative_day1_residual():
    t0 = Epoch.from_iso(T0_ISO, TimeScale.UTC)
    state0 = State(t0, np.array(T0_POS_M), np.array(T0_VEL_MS), Frame.ITRF).to_frame(
        Frame.EME2000
    )

    traj = propagate_numerical(
        state0,
        STEP_S * (len(TRUTH_POS_M) - 1),
        output_step=STEP_S,
        force_models=ForceModelConfig(
            drag=False, solid_tides=True, ocean_tides=True, relativity=True
        ),
        spacecraft=SpacecraftConfig(
            mass_kg=LAGEOS2_MASS_KG,
            geometry=SpacecraftGeometry.sphere(
                area_m2=LAGEOS2_AREA_M2, reflectivity_coefficient=LAGEOS2_CR
            ),
        ),
        integrator=IntegratorConfig.high_precision(),
        progress=False,
    )

    truth = np.asarray(TRUTH_POS_M)
    positions = traj.to_frame(Frame.ITRF).positions
    assert len(positions) == len(truth)
    d = np.linalg.norm(positions - truth, axis=1)

    # t0 sample isolates frame/time conversion from all dynamics.
    assert d[0] < T0_DIFF_BOUND_M
    # The conservative-force day-1 agreement (gravity + third body + SRP +
    # tides + relativity end-to-end against a measured orbit).
    rms = float(np.sqrt(np.mean(d**2)))
    assert rms < DAY1_RMS_BOUND_M
