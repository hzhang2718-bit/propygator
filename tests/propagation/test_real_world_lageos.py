"""Real-world pinned regression: LAGEOS-2 vs. an ILRS precise orbit.

The study Chunk 4 pin (docs/build-plan-real-world-validation.md; evidence in
``experiments/real-world-validation/lageos/``): propagate the pinned ILRS
truth state one day with the conservative force set and require the residual
to stay below the Checkpoint-A number times a generous margin. This guards the
class of bug internal tests structurally cannot see — self-consistent wiring
errors (a frame flip, a force that silently never reaches Orekit) — because
the truth orbit cannot share the misconception.

Fixture: t0 PV + hourly day-1 positions from the ESA ILRS weekly SP3
(satellite L52, SLR08 frame, 2023-04-16, V-records), emitted by
``run_lageos.py --emit-fixture``; provenance in the experiment README.

Tolerance policy (build-plan Chunk 4, binding): thresholds are the measured
values times margins generous enough to absorb orekit-data refreshes
(2019–2024 EOP is final history). They prove "the wiring didn't regress",
not "the number is exact". Measured (results.txt, 2026-07-12): t0 diff
9.3e-10 m; day-1 3D RMS 3.62 m.
"""

