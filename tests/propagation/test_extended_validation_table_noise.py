# GRACE-FO sphere-equivalent parameters (the study's 2026-08-13 geometry;
# experiments/extended-validation/README.md).
A_REF_M2 = 1.0013468
CR = 1.3
# results_table_noise.txt, active_2023 block: "C: ... -> total 596.546 kg",
# "D: ... -> total 597.153 kg" (MAS1B tank gas + dry mass; not re-derivable
# from this fixture, which carries GNV1B only).
MASS_C_KG = 596.546
MASS_D_KG = 597.153

# Measured (600 s cadence): RMS_sphere(C) 227.7 m, RMS_sphere(D) 233.0 m.
RMS_BAND_M = (100.0, 400.0)
# Measured ratio 0.977 against the contract's own 20% bar; 30% absorbs the
# 60 s -> 600 s cadence difference with room to spare.
RATIO_TOL = 0.30


def _rms_sphere_3d(
    t0_iso: str, truth_pos: np.ndarray, truth_vel: np.ndarray, mass_kg: float
) -> float:
    t0 = Epoch.from_iso(t0_iso, TimeScale.TAI)
    state0 = State(t0, truth_pos[0], truth_vel[0], Frame.ITRF).to_frame(Frame.EME2000)
    span_s = STEP_S * (len(truth_pos) - 1)
    traj = propagate_numerical(
        state0,
        span_s,
        output_step=STEP_S,
        force_models=ForceModelConfig(
            drag=True,
            atmosphere_model="NRLMSISE-00",
            srp=True,
            solid_tides=True,
            ocean_tides=True,
            relativity=True,
        ),
        spacecraft=SpacecraftConfig(
            mass_kg=mass_kg,
            geometry=SpacecraftGeometry.sphere(
                area_m2=A_REF_M2,
                drag_coefficient=VariableCd.sphere_default(),
                reflectivity_coefficient=CR,
            ),
        ),
        integrator=IntegratorConfig.high_precision(),
        progress=False,
    )
    positions = traj.to_frame(Frame.ITRF).positions
    assert len(positions) == len(truth_pos)
    diff = positions - truth_pos
    return float(np.sqrt(np.mean(np.sum(diff**2, axis=1))))


def test_gracefo_twin_sphere_table_ratio(orekit):
    rms_c = _rms_sphere_3d(
        T0_ISO_C, np.asarray(TRUTH_POS_M_C), np.asarray(TRUTH_VEL_MS_C), MASS_C_KG
    )
    rms_d = _rms_sphere_3d(
        T0_ISO_D, np.asarray(TRUTH_POS_M_D), np.asarray(TRUTH_VEL_MS_D), MASS_D_KG
    )

    # Sanity band: catches a degenerate run (drag silently off, a broken
    # table lookup, a unit error) rather than a real physical departure.
    assert RMS_BAND_M[0] < rms_c < RMS_BAND_M[1]
    assert RMS_BAND_M[0] < rms_d < RMS_BAND_M[1]

    ratio = rms_c / rms_d
    assert abs(ratio - 1.0) < RATIO_TOL
